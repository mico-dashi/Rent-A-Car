// Generates packages/database/src/types.gen.ts from a live database (public schema)
// in the shape supabase-js expects. Usage: DATABASE_URL=postgres://... node scripts/gen-db-types.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(new URL("../packages/testing/package.json", import.meta.url));
const pg = require("pg");

const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
await client.connect();

const enums = (await client.query(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder)::text[] as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`)).rows;
const enumNames = new Set(enums.map((e) => e.name));

const cols = (await client.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable, c.column_default, c.is_generated, c.is_identity, t.table_type
  from information_schema.columns c join information_schema.tables t on t.table_name = c.table_name and t.table_schema = c.table_schema
  where c.table_schema = 'public' order by c.table_name, c.ordinal_position`)).rows;

const fns = (await client.query(`
  select p.proname as name from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f' order by p.proname`)).rows;

function tsType(c) {
  const udt = c.udt_name.replace(/^_/, "");
  const isArray = c.data_type === "ARRAY";
  let base;
  if (enumNames.has(udt)) base = `Database["public"]["Enums"]["${udt}"]`;
  else if (["int2", "int4", "float4", "float8"].includes(udt)) base = "number";
  else if (["int8", "numeric"].includes(udt)) base = "number"; // PostgREST returns JSON numbers
  else if (udt === "bool") base = "boolean";
  else if (["json", "jsonb"].includes(udt)) base = "Json";
  else base = "string";
  return isArray ? `${base}[]` : base;
}

const byTable = new Map();
for (const c of cols) {
  if (!byTable.has(c.table_name)) byTable.set(c.table_name, { type: c.table_type, cols: [] });
  byTable.get(c.table_name).cols.push(c);
}

let out = `// AUTO-GENERATED by scripts/gen-db-types.mjs — do not edit.\n/* eslint-disable */\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\nexport type Database = {\n  public: {\n    Tables: {\n`;
let views = "";
for (const [name, t] of byTable) {
  const row = t.cols.map((c) => `        ${c.column_name}: ${tsType(c)}${c.is_nullable === "YES" ? " | null" : ""};`).join("\n");
  const insert = t.cols
    .filter((c) => c.is_generated !== "ALWAYS")
    .map((c) => {
      const optional = c.is_nullable === "YES" || c.column_default !== null || c.is_identity === "YES";
      return `        ${c.column_name}${optional ? "?" : ""}: ${tsType(c)}${c.is_nullable === "YES" ? " | null" : ""};`;
    }).join("\n");
  const update = t.cols.filter((c) => c.is_generated !== "ALWAYS")
    .map((c) => `        ${c.column_name}?: ${tsType(c)}${c.is_nullable === "YES" ? " | null" : ""};`).join("\n");
  if (t.type === "VIEW") {
    views += `      ${name}: {\n        Row: {\n${row.replace(/^ {8}/gm, "          ")}\n        };\n        Relationships: [];\n      };\n`;
  } else {
    out += `      ${name}: {\n        Row: {\n${row.replace(/^ {8}/gm, "          ")}\n        };\n        Insert: {\n${insert.replace(/^ {8}/gm, "          ")}\n        };\n        Update: {\n${update.replace(/^ {8}/gm, "          ")}\n        };\n        Relationships: [];\n      };\n`;
  }
}
out += `    };\n    Views: {\n${views}    };\n    Functions: {\n`;
for (const f of fns) out += `      ${f.name}: { Args: Record<string, unknown>; Returns: Json };\n`;
out += `    };\n    Enums: {\n`;
for (const e of enums) out += `      ${e.name}: ${e.labels.map((l) => JSON.stringify(l)).join(" | ")};\n`;
out += `    };\n    CompositeTypes: {};\n  };\n};\n\nexport type Tables<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Row"];\nexport type Views<T extends keyof Database["public"]["Views"]> = Database["public"]["Views"][T]["Row"];\nexport type TablesInsert<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Insert"];\nexport type TablesUpdate<T extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][T]["Update"];\nexport type Enums<T extends keyof Database["public"]["Enums"]> = Database["public"]["Enums"][T];\n`;
writeFileSync(new URL("../packages/database/src/types.gen.ts", import.meta.url), out);
await client.end();
console.log(`generated ${byTable.size} relations, ${fns.length} functions, ${enums.length} enums`);
